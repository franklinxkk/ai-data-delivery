const {chromium}=require('playwright');
const fs=require('fs');const path=require('path');const out=process.env.EVIDENCE_DIR||'tmp-v0011';fs.mkdirSync(out,{recursive:true});const assert=require('assert/strict');
(async()=>{
 const browser=await chromium.launch({...(process.env.BROWSER_PATH?{executablePath:process.env.BROWSER_PATH}:{}),headless:true});
 const page=await browser.newPage({viewport:{width:1440,height:1000}}); const errors=[];page.on('pageerror',e=>errors.push(String(e)));page.on('dialog',d=>d.accept());
 const steps=[]; const state=()=>page.evaluate(async()=>await(await fetch('/api/state',{headers:{'X-Workbench-Token':document.querySelector('meta[name=session-token]').content}})).json());
 await page.goto((process.env.WORKBENCH_URL||'http://127.0.0.1:18841')+'/#data');
 await page.locator('#replace-model').check();
 await page.locator('#file-model').setInputFiles('examples/metadata-reuse/metadata.yaml');
 await page.locator('[data-action="import"][data-kind="model"]').click();
 await page.waitForFunction(()=>document.querySelector('#toast').textContent.includes('已导入'));steps.push('真实文件选择并导入元数据');
 await page.locator('nav [data-page="model"]').click();
 await page.locator('[data-action="derive"]').click();
 await page.waitForFunction(()=>document.querySelector('#toast').textContent.includes('语义候选已保存'));
 let first=await state();assert.equal(first.document.model.ontology.entities.length,2);assert.equal(first.document.model.ontology.relations.length,1);steps.push('点击生成，持久化2对象1关系');
 await page.locator('[data-action="asset-tab"][data-kind="relations"]').click();
 await page.locator('[data-action="edit"][data-kind="relations"]').last().click();
 await page.locator('[name="predicate"]').fill('登记在');
 await page.locator('#edit-form button[type=submit]').click();
 await page.waitForFunction(()=>!document.querySelector('dialog').open);
 await page.locator('[data-action=asset-tab][data-kind=metrics]').click();
 await page.locator('[data-action=edit][data-kind=metrics]').last().click();
 await page.locator('[name=time_requirement]').selectOption('current');
 assert.equal(await page.locator('[name=time_field]').isVisible(),false);
 await page.locator('#edit-form button[type=submit]').click();
 await page.waitForFunction(()=>!document.querySelector('dialog').open);
 let edited=await state();
 assert.equal(edited.document.model.metrics[0].time_requirement,'current');
 assert.equal(edited.gaps.some(g=>g.property==='time_field'),false);
 steps.push('真实编辑当前状态指标，时间字段隐藏，保存重读不再要求虚构时间字段');assert.equal(edited.document.model.ontology.relations[0].predicate,'登记在');steps.push('编辑业务关系并保存');
 await page.reload();await page.locator('[data-action="derive"]').click();
 await page.waitForFunction(()=>document.querySelector('#toast').textContent.includes('语义候选已保存'));
 let repeated=await state();assert.equal(repeated.revision,edited.revision);assert.equal(repeated.document.model.ontology.relations[0].predicate,'登记在');steps.push('重开后重复生成，无重复对象、不增加修订、不覆盖人工内容');
 await page.screenshot({path:path.join(out,'workbench.png'),fullPage:true});assert.deepEqual(errors,[]);
 fs.writeFileSync(path.join(out,'browser-evidence.json'),JSON.stringify({browser:'Chromium family via Playwright',scope:'local workbench UI and its SQLite; synthetic metadata',steps,errors,revision:repeated.revision},null,2));
 await browser.close();console.log(JSON.stringify({steps,errors}));
})().catch(e=>{console.error(e);process.exit(1)});
